def variants():
    """Systematic sweep rows to reach 50: income × expense ratios × debt states."""
    rows = []
    incomes = [40_000, 75_000, 150_000, 300_000]
    for inc in incomes:
        exp = int(inc * 0.7)
        # healthy saver
        rows.append(p(f"sweep-healthy-{inc}", inc, exp, exp * 7,
                      expect=["invest_allocation"], note="sweep: healthy"))
        # thin buffer
        rows.append(p(f"sweep-thinbuffer-{inc}", inc, exp, exp * 2,
                      expect=["emergency_fund", "invest_allocation"], note="sweep: EF first"))
        # expensive debt
        rows.append(p(f"sweep-ccdebt-{inc}", inc, exp, exp * 7, int(inc * 1.2), 40.0,
                      expect=["debt", "invest_allocation"], note="sweep: prepay first"))
        # under water
        rows.append(p(f"sweep-deficit-{inc}", inc, int(inc * 1.1), exp,
                      expect=["stabilize", "emergency_fund"],
                      note="sweep: deficit + sub-month runway buffer card"))
        # dependents uncovered
        rows.append(p(f"sweep-uncovered-{inc}", inc, exp, exp * 7, dependents=True,
                      expect=["insurance", "invest_allocation"], note="sweep: cover gap"))
        # stage-2 EF
        rows.append(p(f"sweep-ef2-{inc}", inc, exp, exp * 4,
                      expect=["emergency_fund", "invest_allocation"], note="sweep: EF 3→6"))
    return rows


def main() -> None:
    profiles = PROFILES + variants()
    assert len(profiles) == 50, f"golden set must be 50, got {len(profiles)}"
    names = [x["name"] for x in profiles]
    assert len(set(names)) == 50, "duplicate names"
    OUT.write_text(json.dumps(profiles, indent=2))
    print(f"wrote {len(profiles)} profiles to {OUT}")


if __name__ == "__main__":
    main()
